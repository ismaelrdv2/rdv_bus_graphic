import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8');
const workflow=read('.github/workflows/desktop-build.yml');
const app=JSON.parse(read('package.json'));
const tauri=JSON.parse(read('src-tauri/tauri.conf.json'));
assert.equal(app.version,'0.1.0-alpha.9.3.23');
assert.equal(tauri.version,app.version);
assert(workflow.includes('workflow_dispatch:'),'Modo economia: release deve exigir início manual');
assert(workflow.includes("if: github.ref_type == 'tag'"),'Não publicar releases de PR/branches');
assert(workflow.includes('needs: [linux-appimage, windows-exe]'),'Requer ambos builds aprovados');
assert(workflow.includes('git merge-base --is-ancestor HEAD origin/main'),'Tag precisa vir da main');
assert(workflow.includes('gh release create'),'Release oficial não criada');
assert(workflow.includes('*.AppImage')&&workflow.includes('setup*.exe'),'Asset por plataforma ausente');
assert(workflow.includes('SHA256SUMS.txt'),'Checksums ausentes');
const updates=read('src/lib/updateCheck.ts');
assert(updates.includes('releases?per_page=20'));
assert(updates.includes("if(platform==='linux')return /\\.AppImage$/i.test(name);"));
assert(updates.includes('assetName'),'Verificação de asset instalável ausente');
console.log('Publicação das Releases Desktop e seletor de atualização por plataforma: OK.');
