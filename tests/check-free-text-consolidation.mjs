import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
import vm from 'node:vm';
const read=p=>readFileSync(new URL('../'+p,import.meta.url),'utf8');
const source=read('src/lib/freeTextModes.ts');
const js=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const mod={};vm.runInNewContext('(function(exports){'+js+'})',{}, {timeout:1000})(mod);
assert.equal(mod.canonicalFreeTextStyle('legacyHalfBar'),'legacyLabel');
assert.equal(mod.canonicalFreeTextStyle('legacyFullBar'),'legacyLabel');
assert.equal(mod.canonicalFreeTextStyle('legacyPresentationSlide'),'fullPage');
assert.equal(mod.studioOnlyStyle('classic'),true);
assert.equal(mod.studioOnlyStyle('technicalAlpha1'),true);
for(const x of ['newsLabel','newsTicker','newsLowerThird','newsSlide'])assert(mod.studioOnlyStyle(x));
for(const x of ['legacyLabel','legacyPresentationBar','technicalBar','fullTechnical','fullPage'])assert(!mod.studioOnlyStyle(x));
assert.equal(mod.labelBarDimensions('small',1920).width,550);
assert.equal(mod.labelBarDimensions('medium',1920).width,960);
assert.equal(mod.labelBarDimensions('large',1920).width,1550);
assert.equal(mod.labelBarDimensions('large',1080).width,1080);
const sample={kind:'freeText',fields:{line1:'Texto extenso para rolar',line2:'Outra linha'},style:{fontSize:30,scaleX:1,scaleY:1},freeTextIcon:'none'};
assert(mod.estimatedLabelWidth(sample,1920)>220);
const legacy=read('src/components/LegacyShape.svelte');
const studio=read('src/components/HudShape.svelte');
const tv=read('src/components/BroadcastShape.svelte');
assert(legacy.includes('compactTextWeights(compactLabel || freeBarPresentation'));
assert(legacy.includes('fields.line2 && element.showFullPageNote!==false'));
assert(legacy.includes('text-anchor="middle"')&&legacy.includes('labelWeights.second'));
assert(studio.includes("studioOnlyStyle(element.freeTextStyle)"));
assert(studio.includes('element.showFullPageNote!==false'));
assert(studio.includes('rich.scrollLine1 && compactWeights.stacked'));
assert(studio.includes('rich.scrollLine2 && compactWeights.stacked'));
assert(studio.includes('studioPresentationBar && !compactWeights.stacked'));
assert(studio.includes('studioPresentationBar && compactWeights.stacked'));
assert(tv.includes("text.replace(/\\r\\n?/g,'\\n').split('\\n')"));
assert(tv.includes("bullet==='dots'")&&tv.includes("bullet==='chevrons'")&&tv.includes("bullet==='numbers'"));
assert(tv.includes('slideLineStep')&&tv.includes('broadcast-body-'));
const userInterface=read('src/components/PropertiesPanel.svelte'),driver=read('src/App.svelte');

assert(driver.includes('onLabelBarSize='));
assert(driver.includes('onAutoFitLabel='));
assert(driver.includes('onFreeTextNote='));
assert(userInterface.includes('on:change={event=>onLabelBarSize'));
assert(userInterface.includes('onFreeTextNote'));
assert(!userInterface.includes('<option value="legacyHalfBar">'));
assert(!userInterface.includes('<option value="legacyFullBar">'));
assert(!userInterface.includes('<option value="legacyPresentationSlide">'));
const validation=read('src/lib/validation.ts');
assert(validation.includes('canonicalFreeTextStyle'));
assert(validation.includes('studioOnlyStyle(freeTextStyle)'));

console.log('Modos de texto livre, migração, notas e marcadores: OK');
